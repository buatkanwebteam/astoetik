// Generates supabase/seed.sql from the same TypeScript seed used in demo mode.
// Usage: npm run seed:sql
import { register } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

register("./ts-resolve.mjs", pathToFileURL(fileURLToPath(import.meta.url)));

const { PRODUCTS } = await import("../src/data/products.ts");
const { PRODUCT_FAQS } = await import("../src/data/faqs.ts");
const { generateSocialMetrics, generateSocialPosts } = await import("../src/data/dummy.ts");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

function insert(table, cols, rows) {
  if (rows.length === 0) return "";
  const values = rows.map((r) => `  (${r.join(", ")})`).join(",\n");
  return `insert into ${table} (${cols.join(", ")}) values\n${values};\n`;
}

const now = new Date();
const out = [
  "-- ASTERA-X seed data. Generated by scripts/generate-seed.mjs; do not edit by hand.",
  `-- Generated at ${now.toISOString()}. Dummy analytics cover the 90 days before this date.`,
  "-- Run after schema.sql.",
  "",
  "begin;",
  "",
  insert(
    "products",
    ["code", "name", "category", "price", "specs", "tkdn", "sni", "image", "gallery", "marketplace_links", "note"],
    PRODUCTS.map((p) => [q(p.code), q(p.name), q(p.category), p.price, j(p.specs), q(p.tkdn), p.sni, q(p.image), j(p.gallery), j(p.marketplaceLinks), q(p.note)]),
  ),
  insert(
    "product_faqs",
    ["id", "product_code", "question", "answer", "source"],
    PRODUCT_FAQS.map((f) => [q(f.id), q(f.productCode), q(f.question), q(f.answer), q(f.source)]),
  ),
  "-- DATA DUMMY: social analytics",
  insert(
    "social_metrics",
    ["platform", "date", "impressions", "engagement", "profile_visits", "marketplace_clicks", "purchases", "followers"],
    generateSocialMetrics(now).map((m) => [q(m.platform), q(m.date), m.impressions, m.engagement, m.profileVisits, m.marketplaceClicks, m.purchases, m.followers]),
  ),
  insert(
    "social_posts",
    ["id", "platform", "title", "posted_at", "format", "impressions", "likes", "comments", "shares", "saves", "clicks", "purchases"],
    generateSocialPosts(now).map((p) => [q(p.id), q(p.platform), q(p.title), q(p.postedAt), q(p.format), p.impressions, p.likes, p.comments, p.shares, p.saves, p.clicks, p.purchases]),
  ),
  "commit;",
  "",
];

const target = new URL("../supabase/seed.sql", import.meta.url);
writeFileSync(target, out.join("\n"));
console.log(`Wrote ${fileURLToPath(target)}: ${PRODUCTS.length} products, ${PRODUCT_FAQS.length} FAQs`);
